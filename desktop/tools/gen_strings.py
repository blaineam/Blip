#!/usr/bin/env python3
"""Generates crates/core/src/strings.rs: Blip for Windows/Linux UI strings in the Mac app's 8
languages.

Every translated key in the Mac string catalog (Blip/Resources/Localizable.xcstrings) is carried
over verbatim, so both apps say the same thing. Desktop-only strings live in
tools/desktop_strings.json as {"English key": {"de": ..., "es": ..., ...}}. Run from desktop/:
    python3 tools/gen_strings.py
"""
import json
import pathlib
import sys

LANGS = ["de", "es", "fr", "it", "ja", "ko", "pt-BR", "zh-Hans"]
ROOT = pathlib.Path(__file__).resolve().parent.parent
MAC = json.loads((ROOT.parent / "Blip/Resources/Localizable.xcstrings").read_text(encoding="utf-8"))["strings"]
OWN = json.loads((ROOT / "tools/desktop_strings.json").read_text(encoding="utf-8"))

table = {}
for key, entry in MAC.items():
    if not key or entry.get("shouldTranslate") is False:
        continue
    locs = entry.get("localizations", {})
    row = []
    for lang in LANGS:
        unit = locs.get(lang, {}).get("stringUnit", {})
        row.append(unit.get("value", "") if unit.get("state") in ("translated", "needs_review", None) else "")
    if any(row):
        table[key] = row

missing = []
for key, tr in OWN.items():
    if key.startswith("//"):
        continue
    row = [tr.get(lang, "") for lang in LANGS]
    missing += [f"{key!r} → {lang}" for lang, v in zip(LANGS, row) if not v]
    table[key] = row  # desktop wording wins where both exist

if missing:
    sys.exit("desktop_strings.json is missing translations:\n  " + "\n  ".join(missing))


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


# Rust sorts &str by bytes; Python sorts str by code point — identical for UTF-8.
keys = sorted(table, key=lambda k: k.encode("utf-8"))
out = [
    "// Generated by tools/gen_strings.py. Do not edit by hand.",
    f"// Columns: {', '.join(LANGS)}.",
    "",
    f"pub const LANGS: [&str; {len(LANGS)}] = [{', '.join(lit(l) for l in LANGS)}];",
    "",
    f"pub static TABLE: [(&str, [&str; {len(LANGS)}]); {len(keys)}] = [",
]
for k in keys:
    out.append(f"    ({lit(k)}, [{', '.join(lit(v) for v in table[k])}]),")
out.append("];")
(ROOT / "crates/core/src/strings.rs").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{len(keys)} strings ({len(OWN)} desktop-only)")
